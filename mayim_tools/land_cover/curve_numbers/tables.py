"""Curve-number tables and the default land-cover lookups - no QGIS, no GDAL.

Two tables are carried:

* SCS-SA: Schulze, Schmidt & Smithers (2004), Visual SCS-SA User Manual,
  Table 5.1 (initial curve numbers CN-II) for the groups A, A/B, B, B/C, C,
  C/D and D. Transcribed from the manual. Two printing slips are corrected
  in the descriptions only (the values are as printed): the second "open
  spaces" row is the fair condition (50-75 % grass cover, it repeats the
  veld-fair values) and "commercial / business areas" is 85 % impervious.
* TR-55: USDA-SCS (1986), Technical Release 55, Tables 2-2a to 2-2d (the
  same values as NEH 630 Chapter 9) for A, B, C and D; the intermediate
  columns are blank and are interpolated when an intermediate group needs
  them. Where TR-55 and Table 5.1 share a row (veld / pasture, woods, row
  crops, small grain, urban) the A, B, C and D values agree.

Row identifiers are "<table>:<key>". A lookup may combine rows with "+"
(their mean, e.g. a fair condition between a high and a low stormflow row)
or give a constant with "const:<CN>".
"""

from __future__ import annotations

from dataclasses import dataclass

GROUPS = ("A", "A/B", "B", "B/C", "C", "C/D", "D")
BASIC = ("A", "B", "C", "D")


@dataclass(frozen=True)
class CnRow:
    key: str
    cover: str
    description: str
    values: tuple  # 7 values in GROUPS order; None where not given


def _sa(key, cover, desc, *vals):
    assert len(vals) == 7, key
    return CnRow(f"scs_sa:{key}", cover, desc, tuple(float(v) for v in vals))


def _tr(key, cover, desc, a, b, c, d):
    vals = (a, None, b, None, c, None, d)
    return CnRow(
        f"tr55:{key}",
        cover,
        desc,
        tuple(None if v is None else float(v) for v in vals),
    )


