def table_of(key: str) -> str:
    return key.split(":", 1)[0]


def row_values(spec: str) -> tuple:
    """Values (GROUPS order, None where missing) of a row spec: one row key,
    several joined by '+' (their mean) or 'const:<CN>'."""
    spec = spec.strip()
    if spec.startswith("const:"):
        v = float(spec.split(":", 1)[1])
        return (v,) * len(GROUPS)
    parts = [p.strip() for p in spec.split("+") if p.strip()]
    if not parts:
        raise KeyError("empty row specification")
    rows = []
    for p in parts:
        if p not in ROWS:
            raise KeyError(f"unknown curve-number table row '{p}'")
        rows.append(ROWS[p].values)
    out = []
    for i in range(len(GROUPS)):
        vals = [r[i] for r in rows]
        out.append(None if any(v is None for v in vals) else sum(vals) / len(vals))
    return tuple(out)


def describe(spec: str) -> str:
    spec = spec.strip()
    if spec.startswith("const:"):
        return f"Constant CN {spec.split(':', 1)[1]}"
    parts = [p.strip() for p in spec.split("+")]
    text = "; ".join(f"{ROWS[p].cover}: {ROWS[p].description}" for p in parts)
    return ("Mean of " if len(parts) > 1 else "") + text


